import streamlit as st

st.title("ℹ️ About DebtAtlas")

st.markdown(
    "DebtAtlas is an accountability tool designed to make public debt visible to the people who ultimately bear it. "
    "By consolidating federal, state, and local liabilities into a single per-capita burden, DebtAtlas helps citizens, journalists, and policymakers understand the full fiscal responsibility behind every taxpayer."
)

st.markdown("---")

st.subheader("Why DebtAtlas Exists")
st.markdown(
    "Debt reporting today is fragmented across different jurisdictions and financial frameworks. This fragmentation hides the collective impact of government borrowing on individuals across the United States."
)

st.markdown("### What DebtAtlas Measures")
st.markdown(
    "* A **federal layer** representing total national debt distributed per resident.\n"
    "* A **state layer** representing state-issued structural debt per resident.\n"
    "* A **municipal/local layer** representing the average local government debt burden per resident."
)

st.markdown("### Accountability Through Transparency")
st.markdown(
    "DebtAtlas makes it easier to compare how different states and local jurisdictions manage debt, without masking the national context. "
    "This tool is intended to support more informed public debate, stronger fiscal oversight, and clearer accountability for elected officials and financial stewards."
)

st.markdown("---")

st.subheader("How to Use This Project")
st.markdown(
    "Navigate the dashboard to see the unified debt burden across states, then explore the Sources and Methods page to understand the data provenance and calculation rules that underpin every figure." 
)
